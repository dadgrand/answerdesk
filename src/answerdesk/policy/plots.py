"""Artifact plots without a plotting dependency.

The acceptance for t8 asks for the risk–coverage curve and the reliability diagram to be
*produced and plotted*. Matplotlib is a base dependency as of the shared re-lock, but the
policy smoke run must also work from a bare install, so this module:

* tries matplotlib with the non-interactive ``Agg`` backend and writes a PNG **and** an SVG
  when it is importable;
* otherwise writes a hand-rolled SVG with the same axes, curve and labels.

Both paths are deterministic (no timestamps, fixed sizes, no RNG), so a report can be
re-generated byte-for-byte — which is what makes a plotted number defensible (§18.2).

    # AT-ESC-07  # AT-EVL-06
"""

from __future__ import annotations

import itertools
import math
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from answerdesk.policy.metrics import ReliabilityBin, RiskCoveragePoint


def _svg_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )


def _minimal_svg(
    *,
    title: str,
    x_label: str,
    y_label: str,
    series: Sequence[tuple[str, Sequence[tuple[float, float]], str]],
    width: int = 640,
    height: int = 420,
) -> str:
    """A self-contained SVG chart: one or more polylines over a unit square."""
    left, right, top, bottom = 70, width - 30, 40, height - 60
    plot_w, plot_h = right - left, bottom - top

    def to_x(value: float) -> float:
        return left + value * plot_w

    def to_y(value: float) -> float:
        return bottom - value * plot_h

    parts: list[str] = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-label="{_svg_escape(title)}">',
        '<rect width="100%" height="100%" fill="#ffffff"/>',
        f'<text x="{left}" y="24" font-family="monospace" font-size="14">'
        f"{_svg_escape(title)}</text>",
    ]
    for step in range(6):
        value = step / 5
        x = to_x(value)
        y = to_y(value)
        parts.append(
            f'<line x1="{x:.2f}" y1="{top}" x2="{x:.2f}" y2="{bottom}" stroke="#e5e5e5" '
            'stroke-width="1"/>'
        )
        parts.append(
            f'<line x1="{left}" y1="{y:.2f}" x2="{right}" y2="{y:.2f}" stroke="#e5e5e5" '
            'stroke-width="1"/>'
        )
        parts.append(
            f'<text x="{x:.2f}" y="{bottom + 18}" font-family="monospace" font-size="10" '
            f'text-anchor="middle">{value:.1f}</text>'
        )
        parts.append(
            f'<text x="{left - 8}" y="{y + 3:.2f}" font-family="monospace" font-size="10" '
            f'text-anchor="end">{value:.1f}</text>'
        )
    parts.append(
        f'<line x1="{left}" y1="{bottom}" x2="{right}" y2="{bottom}" stroke="#333" '
        'stroke-width="1"/>'
    )
    parts.append(
        f'<line x1="{left}" y1="{top}" x2="{left}" y2="{bottom}" stroke="#333" stroke-width="1"/>'
    )
    for index, (name, points, colour) in enumerate(series):
        if not points:
            continue
        path = " ".join(
            f"{to_x(min(1.0, max(0.0, x))):.2f},{to_y(min(1.0, max(0.0, y))):.2f}"
            for x, y in points
        )
        parts.append(f'<polyline points="{path}" fill="none" stroke="{colour}" stroke-width="2"/>')
        parts.append(
            f'<text x="{left + 10}" y="{top + 18 + index * 16}" font-family="monospace" '
            f'font-size="11" fill="{colour}">{_svg_escape(name)}</text>'
        )
    parts.append(
        f'<text x="{(left + right) / 2:.0f}" y="{height - 16}" font-family="monospace" '
        f'font-size="11" text-anchor="middle">{_svg_escape(x_label)}</text>'
    )
    parts.append(
        f'<text x="16" y="{(top + bottom) / 2:.0f}" font-family="monospace" font-size="11" '
        f'transform="rotate(-90 16 {(top + bottom) / 2:.0f})" text-anchor="middle">'
        f"{_svg_escape(y_label)}</text>"
    )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def _matplotlib_axes(title: str, x_label: str, y_label: str) -> tuple[Any, Any] | None:
    try:  # pragma: no cover - exercised only where matplotlib is installed
        import matplotlib

        matplotlib.use("Agg", force=True)
        import matplotlib.pyplot as plt
    except Exception:  # pragma: no cover - bare install
        return None
    figure, axes = plt.subplots(figsize=(6.4, 4.2), dpi=100)
    axes.set_title(title)
    axes.set_xlabel(x_label)
    axes.set_ylabel(y_label)
    axes.set_xlim(0.0, 1.0)
    axes.set_ylim(0.0, 1.0)
    axes.grid(True, alpha=0.3)
    return figure, axes


def plot_risk_coverage(
    curve: Sequence[RiskCoveragePoint],
    path: str | Path,
    *,
    alpha: float | None = None,
    coverage_at_operating_point: float | None = None,
) -> list[Path]:
    """Draw risk vs coverage (plus the α line and the operating point when given)."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    points = [(point.coverage, point.risk) for point in curve]
    written: list[Path] = []

    axes_pair = _matplotlib_axes("Risk-coverage", "coverage", "risk")
    if axes_pair is not None:  # pragma: no cover - depends on matplotlib
        figure, axes = axes_pair
        if points:
            axes.plot([p[0] for p in points], [p[1] for p in points], color="#1f77b4", lw=2)
        if alpha is not None:
            axes.axhline(alpha, color="#d62728", ls="--", lw=1, label=f"alpha={alpha}")
        if coverage_at_operating_point is not None:
            axes.axvline(coverage_at_operating_point, color="#2ca02c", ls=":", lw=1)
        axes.legend(loc="upper left")
        png = target.with_suffix(".png")
        svg = target.with_suffix(".svg")
        figure.tight_layout()
        figure.savefig(png)
        figure.savefig(svg, format="svg", metadata={"Date": None})
        import matplotlib.pyplot as plt

        plt.close(figure)
        written.extend([png, svg])
        return written

    series: list[tuple[str, Sequence[tuple[float, float]], str]] = [
        ("risk-coverage", points, "#1f77b4")
    ]
    if alpha is not None:
        series.append((f"alpha={alpha}", [(0.0, alpha), (1.0, alpha)], "#d62728"))
    svg_path = target.with_suffix(".svg")
    svg_path.write_text(
        _minimal_svg(
            title="Risk-coverage",
            x_label="coverage",
            y_label="risk",
            series=series,
        ),
        encoding="utf-8",
    )
    written.append(svg_path)
    return written


def plot_reliability(
    bins: Sequence[ReliabilityBin],
    path: str | Path,
    *,
    ece: float | None = None,
) -> list[Path]:
    """Draw the reliability diagram: accuracy vs mean confidence, with the diagonal."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    points = [(row.mean_confidence, row.accuracy) for row in bins if row.count > 0]
    written: list[Path] = []

    axes_pair = _matplotlib_axes("Reliability", "mean confidence", "accuracy")
    if axes_pair is not None:  # pragma: no cover - depends on matplotlib
        figure, axes = axes_pair
        axes.plot([0.0, 1.0], [0.0, 1.0], color="#999999", ls="--", lw=1)
        if points:
            axes.plot([p[0] for p in points], [p[1] for p in points], marker="o", color="#1f77b4")
        if ece is not None:
            axes.set_title(f"Reliability (ECE={ece:.3f})")
        png = target.with_suffix(".png")
        svg = target.with_suffix(".svg")
        figure.tight_layout()
        figure.savefig(png)
        figure.savefig(svg, format="svg", metadata={"Date": None})
        import matplotlib.pyplot as plt

        plt.close(figure)
        written.extend([png, svg])
        return written

    series: list[tuple[str, Sequence[tuple[float, float]], str]] = [
        ("perfect", [(0.0, 0.0), (1.0, 1.0)], "#999999"),
        ("observed", points, "#1f77b4"),
    ]
    title = "Reliability" if ece is None else f"Reliability (ECE={ece:.3f})"
    svg_path = target.with_suffix(".svg")
    svg_path.write_text(
        _minimal_svg(
            title=title,
            x_label="mean confidence",
            y_label="accuracy",
            series=series,
        ),
        encoding="utf-8",
    )
    written.append(svg_path)
    return written


def plot_hit_rate_vs_error(
    points: Sequence[tuple[float, float]],
    path: str | Path,
    *,
    epsilon: float | None = None,
) -> list[Path]:
    """Cache hit-rate vs wrong-hit-rate curve (vCache-style, requirements §9.6)."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    series: list[tuple[str, Sequence[tuple[float, float]], str]] = [
        ("hit-rate vs wrong-hit-rate", points, "#1f77b4")
    ]
    if epsilon is not None:
        series.append((f"epsilon={epsilon}", [(epsilon, 0.0), (epsilon, 1.0)], "#d62728"))
    svg_path = target.with_suffix(".svg")
    svg_path.write_text(
        _minimal_svg(
            title="Cache: hit rate vs wrong-hit rate",
            x_label="wrong-hit rate",
            y_label="hit rate",
            series=series,
        ),
        encoding="utf-8",
    )
    return [svg_path]


def line_length(points: Sequence[tuple[float, float]]) -> float:
    """Total polyline length — a tiny sanity metric used by the plot tests."""
    return math.fsum(math.dist(left, right) for left, right in itertools.pairwise(points))


