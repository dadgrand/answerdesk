def identifier_findings(texts: list[str]) -> list[str]:
    """Every violation of the reserved-identifier policy found in ``texts``."""
    findings: list[str] = []
    for text in texts:
        for match in _IPV4_RE.finditer(text):
            if not match.group(0).startswith(_RESERVED_IPV4_PREFIXES):
                findings.append(f"non-reserved IPv4 {match.group(0)!r}")
        phone_spans = [match.span() for match in _PHONE_RE.finditer(text)]
        for match in _EMAIL_RE.finditer(text):
            domain = match.group(1).lower()
            if domain not in ALLOWED_DOMAINS:
                findings.append(f"non-example email domain {domain!r}")
        for match in _PHONE_RE.finditer(text):
            candidate = " ".join(match.group(0).split())
            if not any(_phone_matches(candidate, reserved) for reserved in PHONE_RANGES.values()):
                findings.append(f"phone outside reserved ranges {candidate!r}")
        for match in _PAN_CANDIDATE_RE.finditer(text):
            if _overlaps(match.span(), phone_spans):
                continue
            digits = re.sub(r"[ -]", "", match.group(0))
            if not 13 <= len(digits) <= 19:
                continue
            if digits not in TEST_PANS and not luhn_valid(digits):
                findings.append(f"card-like number {match.group(0)!r}")
        lowered = text.lower()
        for token in DENYLISTED_TOKENS:
            if token in lowered:
                findings.append(f"denylisted brand token {token!r}")
    return sorted(set(findings))


def _overlaps(span: tuple[int, int], spans: list[tuple[int, int]]) -> bool:
    start, end = span
    return any(start < other_end and other_start < end for other_start, other_end in spans)


def _phone_matches(candidate: str, reserved: str) -> bool:
    """True when ``candidate`` only differs from a reserved range in its zeros."""
    pattern = "^" + re.escape(reserved).replace("0", r"\d") + "$"
    return re.match(pattern, candidate) is not None


