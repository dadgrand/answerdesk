class SyntheticConfig(IngestModel):
    """Generation knobs. Every number here is recorded in the manifest."""

    seed: int = DEMO_SEED
    docs_per_locale: int = 135
    locales: tuple[str, ...] = LOCALES
    license: str = "CC0-1.0"
    duplicate_every: int = 61
    queries_per_doc: int = 4
    sentences_per_section: int = 2

    @model_validator(mode="after")
    def _bounds(self) -> SyntheticConfig:
        if self.docs_per_locale < 1:
            raise ValueError("docs_per_locale must be >= 1")
        if not self.locales:
            raise ValueError("at least one locale is required")
        if self.duplicate_every < 2:
            raise ValueError("duplicate_every must be >= 2")
        if self.queries_per_doc < 1:
            raise ValueError("queries_per_doc must be >= 1")
        return self


