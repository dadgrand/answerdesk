def _duplicates(
    documents: list[GeneratedDocument], cfg: SyntheticConfig
) -> list[GeneratedDocument]:
    """Emit a near-copy of an earlier document every ``duplicate_every`` documents."""
    duplicates: list[GeneratedDocument] = []
    for position, source in enumerate(documents):
        if position == 0 or position % cfg.duplicate_every != 0:
            continue
        head, separator, body = source.text.partition("---\n\n")
        duplicate_id = f"{source.doc_id}-dup"
        head = re.sub(r"(?m)^doc_id:.*$", f'doc_id: "{duplicate_id}"', head)
        lines = body.split("\n")
        for index, line in enumerate(lines):
            if len(line) > 60 and line.startswith(("1. ", "2. ", "Q: ")):
                lines[index] = f"{line} {_duplicate_tail(source.locale)}"
                break
        duplicates.append(
            GeneratedDocument(
                doc_id=duplicate_id,
                locale=source.locale,
                intent=source.intent,
                title=f"{source.title} (copy)",
                text=head + separator + "\n".join(lines),
                archetype=source.archetype,
                is_duplicate_of=source.doc_id,
            )
        )
    return duplicates


def _duplicate_tail(locale: str) -> str:
    return {
        "ru": "Уточните, пожалуйста, детали.",
        "tg": "Лутфан тафсилотро аниқ кунед.",
        "uz": "Iltimos, tafsilotlarni aniqlang.",
        "ky": "Сураныч, чоо-жайын тактаңыз.",
        "tr": "Lütfen ayrıntıları belirtin.",
        "zh": "请说明详细信息。",
    }.get(locale, "Please clarify.")


