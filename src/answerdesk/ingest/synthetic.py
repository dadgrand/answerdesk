def _interleaved_plan(counts: dict[str, int]) -> tuple[str, ...]:
    """Round-robin the categories so even a 9-query slice covers every one of them."""
    remaining = dict(counts)
    plan: list[str] = []
    while any(remaining.values()):
        for category in QUERY_CATEGORIES:
            if remaining[category] > 0:
                plan.append(category)
                remaining[category] -= 1
    return tuple(plan)


