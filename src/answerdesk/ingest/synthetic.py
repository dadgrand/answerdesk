"""Seeded synthetic multilingual support corpus (FR-ING-10, §10.1).

The generator produces three artefacts from one seed:

* **documents** — knowledge-base articles in ``ru/tg/uz/ky/tr/zh`` covering six support
  intents (tariffs, cards, transfers, documents, KYC, complaints), with headings,
  paragraphs, fee tables, numbered procedures and FAQ pairs. The structure is what the
  chunker consumes, so the corpus exercises FR-ING-02 for real.
* **queries** — customer questions derived from the documents, with controlled
  perturbations: typos, intra-sentence code-switching (locale + English product terms),
  numbers/dates and identifiers (order IDs, error codes).
* **near-duplicates** — every ``duplicate_every`` documents a near-copy of an earlier
  one is emitted, so deduplication has something real to remove (FR-ING-06).

Determinism
-----------
Every random choice comes from ``random.Random(f"{seed}:{locale}:{index}")``; no
wall-clock value, no ``hash()``, no dictionary-order dependence. The same seed produces
byte-identical files, and therefore a byte-identical manifest.

Licensing and identifiers (§13.2, §13.4)
----------------------------------------
The corpus is generated by this module and dedicated to the public domain
(``CC0-1.0``). It contains **no real institution names and no real identifiers**: card
numbers are from the documented test-PAN list, orders use ``ORD-YYYY-NNNNNN``, error
codes ``ERR-XXX-NNNN``, domains ``example.com`` and phones only the reserved/fictional
ranges below. :func:`identifier_findings` proves it, and the corpus builder refuses to
write a corpus that fails the scan.
"""

