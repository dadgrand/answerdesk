def generate(
    config: SyntheticConfig | None = None,
) -> tuple[list[GeneratedDocument], list[GeneratedQuery]]:
    """Generate documents and queries for every locale, deterministically.

    A document and its queries are produced by **one** article pass (one RNG, one slot
    draw), so a reference reply can never disagree with the document it belongs to
    (FR-ING-10 aligned-draw contract, docs/ingestion.md §7.2).
    """
    cfg = config or SyntheticConfig()
    documents: list[GeneratedDocument] = []
    queries: list[GeneratedQuery] = []
    for locale in cfg.locales:
        bank = locale_bank(locale)
        articles = [_render_article(bank, index, cfg) for index in range(cfg.docs_per_locale)]
        documents.extend(article.document for article in articles)
        queries.extend(_generate_locale_queries(bank, articles, cfg))
    documents.extend(_duplicates(documents, cfg))
    documents.sort(key=lambda item: item.doc_id)
    queries.sort(key=lambda item: item.query_id)
    return documents, queries


def locale_bank(locale: str) -> LocaleBank:
    """Look up a locale bank, raising a clear error for an unsupported locale."""
    from answerdesk.ingest.synthetic_data import BANKS

    try:
        return BANKS[locale]
    except KeyError as exc:
        supported = ", ".join(sorted(BANKS))
        raise ValueError(f"unsupported locale {locale!r}; supported: {supported}") from exc


