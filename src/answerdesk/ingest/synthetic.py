#: A claim is a sentence, a canonicalised value, or a content token of a reply.
CLAIM_KINDS: tuple[str, ...] = ("sentence", "canonical", "token")


@runtime_checkable
class DocumentLike(Protocol):
    """Anything with a ``doc_id`` and ``text``: a generated article or a loaded Document."""

    doc_id: str
    text: str


class GroundingFinding(IngestModel):
    """One reference claim that is not present in the document it cites."""

    query_id: str
    doc_id: str
    claim_kind: str
    claim: str
    reason: str


@dataclass(frozen=True)
class ReferenceClaim:
    """One parsed claim of a reference reply, with the kind of match it needs."""

    kind: str
    value: str


def reference_claims(reply: str) -> list[ReferenceClaim]:
    """Parse a reference reply into the claims a document must entail.

    Three kinds, strongest first: the **sentences** themselves (verbatim match after
    whitespace normalisation), the **canonical values** (dates, money, codes, PANs) and
    the **content tokens** (every word of three characters or more, case-folded). A reply
    that quotes a different amount, date or identifier than its document fails the second
    and third kinds even when the sentence shape is identical.
    """
    from answerdesk.ingest.loaders import split_sentences

    normalised = _normalise_claim_text(reply)
    if not normalised:
        return []
    claims: list[ReferenceClaim] = []
    seen: set[tuple[str, str]] = set()

    def push(kind: str, value: str) -> None:
        if not value:
            return
        key = (kind, value)
        if key in seen:
            return
        seen.add(key)
        claims.append(ReferenceClaim(kind=kind, value=value))

    for sentence in split_sentences(normalised):
        push("sentence", _normalise_claim_text(sentence))
    for token in canonicalize(normalised):
        push("canonical", token)
    for token in re.findall(r"\w+", normalised):
        if len(token) >= 3:
            push("token", token.casefold())
    return claims


def _normalise_claim_text(text: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", text).casefold().split())


class _DocumentIndex:
    """Pre-computed matching surface of one document (built once per verification)."""

    __slots__ = ("canonical", "text", "tokens")

    def __init__(self, text: str) -> None:
        self.text = _normalise_claim_text(text)
        self.tokens = {token.casefold() for token in re.findall(r"\w+", self.text)}
        self.canonical = set(canonicalize(text))

    def entails(self, claim: ReferenceClaim) -> bool:
        if claim.kind == "sentence":
            return claim.value in self.text
        if claim.kind == "canonical":
            return claim.value in self.canonical or claim.value in self.text
        if claim.kind == "token":
            return claim.value in self.tokens
        raise ValueError(f"unknown claim kind {claim.kind!r}")


def verify_reference_grounding(
    documents: Sequence[DocumentLike], queries: Sequence[GeneratedQuery]
) -> list[GroundingFinding]:
    """Every reference claim of every query must be present in its source document(s).

    Multi-hop queries (t18) carry ``supporting_doc_ids``; a claim may be entailed by any
    one of them, which is exactly what "the answer needs two documents" means. Queries
    marked ``answerable=False`` must carry **no** reference reply, so an unanswerable item
    can never smuggle in an unsupported answer.

    ``documents`` is any record with ``doc_id`` and ``text`` — a generated article or the
    ``answerdesk.contracts.Document`` a loader produced, so the corpus builder applies the
    same gate to the files it is about to write.
    """
    index_by_doc = {document.doc_id: _DocumentIndex(document.text) for document in documents}
    findings: list[GroundingFinding] = []
    for query in queries:
        reply = query.operator_reply
        if not getattr(query, "answerable", True):
            if reply.strip():
                findings.append(
                    GroundingFinding(
                        query_id=query.query_id,
                        doc_id=query.doc_id,
                        claim_kind="answerable",
                        claim=reply[:80],
                        reason="an unanswerable query must not carry a reference reply",
                    )
                )
            continue
        supporting = tuple(getattr(query, "supporting_doc_ids", ()) or (query.doc_id,))
        owners = [index_by_doc[doc_id] for doc_id in supporting if doc_id in index_by_doc]
        missing = [doc_id for doc_id in supporting if doc_id not in index_by_doc]
        if missing:
            findings.append(
                GroundingFinding(
                    query_id=query.query_id,
                    doc_id=query.doc_id,
                    claim_kind="document",
                    claim=", ".join(missing),
                    reason="query cites a document that is not in the corpus",
                )
            )
            continue
        for claim in reference_claims(reply):
            if not any(owner.entails(claim) for owner in owners):
                findings.append(
                    GroundingFinding(
                        query_id=query.query_id,
                        doc_id=query.doc_id,
                        claim_kind=claim.kind,
                        claim=claim.value,
                        reason=f"reference {claim.kind} is absent from its source document(s)",
                    )
                )
    return findings


def grounding_report(
    documents: Sequence[DocumentLike], queries: Sequence[GeneratedQuery]
) -> dict[str, Any]:
    """Manifest-ready summary of the reference-grounding gate."""
    findings = verify_reference_grounding(documents, queries)
    return {
        "checked": len(queries),
        "findings": [finding.model_dump(mode="json") for finding in findings],
    }


