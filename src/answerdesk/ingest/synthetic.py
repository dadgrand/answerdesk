@dataclass(frozen=True)
class _Article:
    """One rendered article plus the context its queries must share (t15, t18)."""

    document: GeneratedDocument
    index: int
    archetype: str
    slots: dict[str, str]
    faqs: list[tuple[str, str]]


def _render_article(bank: LocaleBank, index: int, cfg: SyntheticConfig) -> _Article:
    """Render one article and keep the slot draw its queries must reuse.

    One RNG, one slot draw and one FAQ selection per article: document, question and
    reference reply can never disagree (docs/ingestion.md §7.2). Queries are generated
    afterwards by :func:`_generate_locale_queries`, which receives this context and draws
    nothing new.
    """
    archetype = ARCHETYPES[index % len(ARCHETYPES)]
    intent = ARCHETYPE_INTENT[archetype]
    rng = random.Random(f"{cfg.seed}:{bank.code}:{index}")
    slots = _slots(rng, bank, index)
    payload = bank.intents[intent]
    title = _title(payload, slots, rng, bank)
    sections = _sections(bank, payload, slots, rng, cfg, section_count=4 + index % 2)
    table_rows = _table_rows(bank, payload, slots, rng)
    steps = [step.format_map(slots) for step in payload.procedure_steps or bank.procedure_steps]
    faqs = _faqs(payload, slots, rng)
    body = _render_markdown(
        title=title,
        intro=_intro(bank, payload, slots, rng),
        sections=sections,
        table_heading=bank.table_heading,
        table=bank.table_header,
        table_rows=table_rows,
        procedure_heading=bank.procedure_heading,
        steps=steps,
        faqs=faqs,
        faq_heading=bank.faq_heading,
        contact_heading=bank.contact_heading,
        contact_lines=[line.format_map(slots) for line in bank.contact_lines],
    )
    doc_id = f"syn-{bank.code}-{index:04d}"
    front_matter = _front_matter(
        doc_id=doc_id,
        title=title,
        locale=bank.code,
        intent=intent,
        archetype=archetype,
        license=cfg.license,
        seed=cfg.seed,
    )
    document = GeneratedDocument(
        doc_id=doc_id,
        locale=bank.code,
        intent=archetype,
        title=title,
        text=front_matter + body,
        archetype=archetype,
    )
    return _Article(document=document, index=index, archetype=archetype, slots=slots, faqs=faqs)


def _title(payload: IntentBank, slots: dict[str, str], rng: random.Random, bank: LocaleBank) -> str:
    title = payload.title.format_map(slots)
    if rng.random() < 0.5:
        return title
    return f"{title} — {slots['plan']}"


def _intro(bank: LocaleBank, payload: IntentBank, slots: dict[str, str], rng: random.Random) -> str:
    pool = [*payload.sentences, *bank.generic_sentences]
    picks = _pick(rng, pool, 2)
    return " ".join(part.format_map(slots) for part in picks)


def _sections(
    bank: LocaleBank,
    payload: IntentBank,
    slots: dict[str, str],
    rng: random.Random,
    cfg: SyntheticConfig,
    *,
    section_count: int = 4,
) -> list[tuple[str, list[str]]]:
    headings = list(payload.headings) + list(bank.generic_headings)
    rng.shuffle(headings)
    chosen = headings[:section_count]
    pool = [*payload.sentences, *bank.generic_sentences]
    used: set[str] = set()
    sections: list[tuple[str, list[str]]] = []
    for heading in chosen:
        paragraphs: list[str] = []
        for _ in range(2):
            sentences = _pick(rng, pool, cfg.sentences_per_section + 1, exclude=used)
            used.update(sentences)
            paragraphs.append(" ".join(item.format_map(slots) for item in sentences))
        sections.append((heading.format_map(slots), paragraphs))
    return sections


def _table_rows(
    bank: LocaleBank, payload: IntentBank, slots: dict[str, str], rng: random.Random
) -> list[str]:
    rows = [row.format_map(slots) for row in payload.table_rows]
    rows.extend(row.format_map(slots) for row in bank.table_rows)
    rng.shuffle(rows)
    return rows[:6]


def _faqs(payload: IntentBank, slots: dict[str, str], rng: random.Random) -> list[tuple[str, str]]:
    faqs = list(payload.faqs)
    rng.shuffle(faqs)
    return [(question.format_map(slots), answer.format_map(slots)) for question, answer in faqs[:2]]


def _render_markdown(
    *,
    title: str,
    intro: str,
    sections: list[tuple[str, list[str]]],
    table_heading: str,
    table: tuple[str, str, str, str],
    table_rows: list[str],
    procedure_heading: str,
    steps: list[str],
    faqs: list[tuple[str, str]],
    faq_heading: str,
    contact_heading: str,
    contact_lines: list[str],
) -> str:
    """Render one article. Pipe tables and ``Q:``/``A:`` markers are the loader contract."""
    parts: list[str] = [f"# {title}", "", intro, ""]
    for heading, paragraphs in sections:
        parts.extend([f"## {heading}", ""])
        for paragraph in paragraphs:
            parts.extend([paragraph, ""])
    parts.extend([f"## {table_heading}", "", _render_table(table, table_rows), ""])
    parts.extend([f"## {procedure_heading}", ""])
    parts.extend([f"{position}. {step}" for position, step in enumerate(steps, start=1)])
    parts.append("")
    parts.extend([f"## {faq_heading}", ""])
    for question, answer in faqs:
        parts.extend([f"Q: {question}", f"A: {answer}", ""])
    parts.extend([f"## {contact_heading}", ""])
    parts.extend(contact_lines)
    parts.append("")
    return "\n".join(parts)


def _render_table(header: tuple[str, str, str, str], rows: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    for row in rows:
        cells = [cell.strip() for cell in row.split("|")]
        padded = [*cells, *([""] * (len(header) - len(cells)))]
        lines.append("| " + " | ".join(padded[: len(header)]) + " |")
    return "\n".join(lines)


def _front_matter(
    *,
    doc_id: str,
    title: str,
    locale: str,
    intent: str,
    archetype: str,
    license: str,
    seed: int,
) -> str:
    """YAML front matter with every string quoted (titles contain ``:`` and ``—``)."""

    def scalar(value: str) -> str:
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'

    return (
        "---\n"
        f"doc_id: {scalar(doc_id)}\n"
        f"title: {scalar(title)}\n"
        f"language: {scalar(locale)}\n"
        f"intent: {scalar(intent)}\n"
        f"archetype: {scalar(archetype)}\n"
        f"license: {scalar(license)}\n"
        f"generator: {scalar(f'{GENERATOR_NAME}-v{GENERATOR_VERSION}')}\n"
        f"seed: {seed}\n"
        "---\n\n"
    )


def _pick(
    rng: random.Random, pool: list[str], count: int, *, exclude: set[str] | None = None
) -> list[str]:
    """Deterministic sample without replacement, skipping already-used sentences."""
    candidates = [item for item in pool if not exclude or item not in exclude]
    if not candidates:
        candidates = list(pool)
    rng.shuffle(candidates)
    return candidates[:count]


