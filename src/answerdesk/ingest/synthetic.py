PERTURBATION_CLASSES: tuple[str, ...] = ("typo", "code_switch", "numeric_date", "identifier")


def _generate_locale_queries(
    bank: LocaleBank, articles: list[_Article], cfg: SyntheticConfig
) -> list[GeneratedQuery]:
    """Queries for one locale, covering every category of the t18 plan."""
    by_archetype: dict[str, _Article] = {}
    for article in articles:
        by_archetype.setdefault(article.archetype, article)
    security = by_archetype.get("security_notice")
    queries: list[GeneratedQuery] = []
    noisy_ordinal = 0
    for position, article in enumerate(articles):
        rng = random.Random(f"{cfg.seed}:{bank.code}:{article.index}:queries")
        for slot in range(cfg.queries_per_doc):
            plan_index = (position * cfg.queries_per_doc + slot) % len(_QUERY_PLAN)
            category = _QUERY_PLAN[plan_index]
            queries.append(
                _build_query(
                    bank=bank,
                    article=article,
                    by_archetype=by_archetype,
                    security=security,
                    rng=rng,
                    slot=slot,
                    category=category,
                    noisy_ordinal=noisy_ordinal,
                )
            )
            if category == "noisy_freeform":
                noisy_ordinal += 1
    return queries


def _build_query(
    *,
    bank: LocaleBank,
    article: _Article,
    by_archetype: dict[str, _Article],
    security: _Article | None,
    rng: random.Random,
    slot: int,
    category: str,
    noisy_ordinal: int = 0,
) -> GeneratedQuery:
    """Build one query of ``category`` from the article's own slot draw."""
    document = article.document
    question, reply = article.faqs[slot % len(article.faqs)]
    supporting: tuple[str, ...] = (document.doc_id,)
    answerable = True
    base_text = question
    style = ""
    doc_id = document.doc_id
    archetype = document.archetype
    intent = document.intent
    perturbations: tuple[str, ...] = ()

    if category == "direct":
        pass
    elif category in ("numeric_date", "identifier"):
        question = _perturb(question, category, bank, article.slots, rng, document.text)
        perturbations = (category,)
    elif category == "code_switch":
        question = _inject_code_switch(question, bank, rng)
        perturbations = ("code_switch",)
    elif category == "typo":
        question = _inject_typo_or_transliteration(question, bank, rng, document.locale)
        perturbations = ("typo",)
    elif category == "multi_hop":
        partner_archetype = MULTIHOP_PARTNERS[article.archetype]
        partner = by_archetype.get(partner_archetype)
        if partner is not None and partner.document.doc_id != document.doc_id:
            partner_question, partner_reply = partner.faqs[0]
            question = f"{question} {partner_question}"
            reply = f"{reply} {partner_reply}"
            supporting = (document.doc_id, partner.document.doc_id)
    elif category == "unanswerable":
        question = UNANSWERABLE_QUESTIONS[bank.code][slot % len(UNANSWERABLE_QUESTIONS[bank.code])]
        reply = ""
        answerable = False
    elif category == "noisy_freeform":
        style, question, reply, supporting, doc_id, archetype, intent, base_text = _noisy_query(
            article=article,
            by_archetype=by_archetype,
            bank=bank,
            rng=rng,
            ordinal=noisy_ordinal,
        )
        perturbations = ("noisy_freeform",)
    elif category in ("pii", "injection"):
        target = security or article
        table = PII_QUESTIONS if category == "pii" else INJECTION_QUESTIONS
        options = table[bank.code]
        question = options[slot % len(options)].format_map(article.slots)
        _, target_reply = target.faqs[0]
        reply = target_reply
        supporting = (target.document.doc_id,)
        perturbations = ("pii",) if category == "pii" else ("injection",)
    else:  # pragma: no cover - the plan is a closed set
        raise ValueError(f"unknown query category {category!r}")

    return GeneratedQuery(
        query_id=f"{document.doc_id}-q{slot}",
        locale=document.locale,
        intent=intent,
        doc_id=doc_id,
        text=question,
        base_text=base_text,
        category=category,
        perturbations=perturbations,
        operator_reply=reply,
        archetype=archetype,
        style=style,
        supporting_doc_ids=supporting,
        answerable=answerable,
    )


def _mangle_noisy(
    question: str, style: str, article: _Article, bank: LocaleBank, rng: random.Random
) -> str:
    """Apply one noisy style to a clean question (returns the canonical form on failure)."""
    from answerdesk.ingest import noisy

    if style == "telegraphic":
        return noisy.make_telegraphic(question, bank.code, rng)
    if style == "run_on":
        second = article.faqs[1][0] if len(article.faqs) > 1 else question
        return noisy.make_run_on(question, bank.code, second)
    if style == "dropped_preposition":
        return noisy.drop_prepositions(question, bank.code)
    if style == "translit":
        return _inject_typo_or_transliteration(question, bank, rng, bank.code)
    mangled = noisy.strip_punctuation(noisy.drop_prepositions(question, bank.code))
    return _inject_typo_or_transliteration(mangled, bank, rng, bank.code)


def _noisy_query(
    *,
    article: _Article,
    by_archetype: dict[str, _Article],
    bank: LocaleBank,
    rng: random.Random,
    ordinal: int,
) -> tuple[str, str, str, tuple[str, ...], str, str, str, str]:
    """One noisy free-form query: owner example first, then a deterministic mangling.

    Returns ``(style, question, reply, supporting_doc_ids, doc_id, archetype, intent)``.
    The reply is always a verbatim FAQ answer of the target document, so the t15 grounding
    gate applies unchanged to malformed input.
    """
    from answerdesk.ingest import noisy

    examples = noisy.examples_for(bank.code)
    if ordinal < len(examples):
        example = examples[ordinal]
        target = by_archetype.get(example.archetype) or article
        _, reply = target.faqs[0]
        return (
            example.style,
            example.text,
            reply,
            (target.document.doc_id,),
            target.document.doc_id,
            target.archetype,
            target.document.intent,
            target.faqs[0][0],
        )
    styles = noisy.noisy_styles_for(bank.code)
    start = (ordinal + article.index) % len(styles)
    question, reply = article.faqs[ordinal % len(article.faqs)]
    mangled = ""
    style = styles[start]
    for offset in range(len(styles)):
        candidate_style = styles[(start + offset) % len(styles)]
        candidate = _mangle_noisy(question, candidate_style, article, bank, rng)
        if candidate and candidate != question:
            mangled, style = candidate, candidate_style
            break
    if not mangled:
        # last resort: a doubled final letter is still a realistic keystroke slip
        mangled = f"{question}{question[-1:]}"
        style = "typo_mix"
    return (
        style,
        mangled or question,
        reply,
        (article.document.doc_id,),
        article.document.doc_id,
        article.archetype,
        article.document.intent,
        question,
    )


def _inject_typo_or_transliteration(
    text: str, bank: LocaleBank, rng: random.Random, locale: str
) -> str:
    """Alternate between a keystroke typo and a Latin transliteration (t18)."""
    mapping = TRANSLIT_MAPS.get(locale) or {}
    if mapping and rng.random() < 0.5:
        for source, target in mapping.items():
            if source in text:
                return text.replace(source, target, 1)
    mutated = _inject_typo(text, rng)
    if mutated != text:
        return mutated
    # Short words and CJK need a weaker threshold; a typo query must always be perturbed.
    mutated = _inject_typo(text, rng, min_word_length=3)
    if mutated != text:
        return mutated
    match = re.search(r"[^\W\d_]{2,}", text, re.UNICODE)
    if match:
        word = match.group(0)
        return text[: match.start()] + word[0] + word + text[match.end() :]
    return text


def _fallback_faqs(document: GeneratedDocument) -> list[tuple[str, str]]:
    """Last-resort pair when a bank has no FAQ: derive it from the document itself."""
    from answerdesk.ingest.loaders import split_sentences

    sentences = split_sentences(document.text)
    body = [sentence for sentence in sentences if len(sentence) > 40] or sentences
    answer = body[0] if body else document.title
    return [(f"{document.title}?", answer)]


def _perturb(
    text: str,
    klass: str,
    bank: LocaleBank,
    slots: dict[str, str],
    rng: random.Random,
    document_text: str,
) -> str:
    if klass == "typo":
        return _inject_typo(text, rng)
    if klass == "code_switch":
        return _inject_code_switch(text, bank, rng)
    if klass == "numeric_date":
        return _inject_date(text, bank, slots, rng, document_text)
    if klass == "identifier":
        return _inject_identifier(text, slots, rng, document_text)
    raise ValueError(f"unknown perturbation class {klass!r}")


def _inject_typo(text: str, rng: random.Random, min_word_length: int = 5) -> str:
    """Swap/copy/drop one character inside a word (never inside a digit run)."""
    words = list(re.finditer(rf"[^\W\d_]{{{max(1, min_word_length)},}}", text, re.UNICODE))
    if not words:
        return text
    match = rng.choice(words)
    word = match.group(0)
    length = len(word)
    position = rng.randrange(0, length)
    operation = rng.choice(("swap", "drop", "double"))
    if operation == "swap":
        if length < 2:
            return text
        index = min(position, length - 2)
        mutated = f"{word[:index]}{word[index + 1]}{word[index]}{word[index + 2 :]}"
    elif operation == "drop":
        if length < 2:
            return text
        mutated = f"{word[:position]}{word[position + 1 :]}"
    else:
        mutated = f"{word[:position]}{word[position]}{word[position:]}"
    if mutated == word:  # swapping two identical letters changes nothing
        mutated = f"{word[:position]}{word[position]}{word[position:]}"
    return text[: match.start()] + mutated + text[match.end() :]


def _inject_code_switch(text: str, bank: LocaleBank, rng: random.Random) -> str:
    """Replace one local-language product word with its English term (locale + EN).

    A whole-word replacement is preferred so a stem is never mangled (``тариф`` must
    not turn ``тарифи`` into ``planи``); when no whole word is present the English term
    is appended in parentheses, which is what bilingual customers actually type.
    """
    pairs = list(bank.code_switch_pairs)
    rng.shuffle(pairs)
    for local, english in pairs:
        if not local:
            continue
        pattern = rf"(?<![\w]){re.escape(local)}(?![\w])"
        if re.search(pattern, text):
            return re.sub(pattern, english, text, count=1)
        if _is_cjk(local) and local in text:
            return text.replace(local, english, 1)
    _, english = rng.choice(pairs)
    return f"{text} ({english})"


def _is_cjk(text: str) -> bool:
    return bool(text) and all("\u4e00" <= char <= "\u9fff" for char in text)


def _inject_date(
    text: str,
    bank: LocaleBank,
    slots: dict[str, str],
    rng: random.Random,
    document_text: str,
) -> str:
    """Append a date clause whose date is one the document actually states (FR-ING-10).

    The article's contact block always carries ``{date}`` ("as of …"), so the preferred
    candidate is guaranteed grounded; other dates found in the text are acceptable too.
    """
    candidates = [value for value in _dates_in_text(document_text) if value]
    preferred = slots.get("date", "")
    if preferred and preferred in document_text:
        candidates.insert(0, preferred)
    if not candidates:
        return text
    chosen = rng.choice(candidates)
    template = rng.choice(bank.date_templates)
    clause = template.format_map({**slots, "date": chosen})
    return f"{text} {clause}"


def _inject_identifier(
    text: str, slots: dict[str, str], rng: random.Random, document_text: str
) -> str:
    """Append an identifier that appears in the document (order id, error code, PAN)."""
    candidates = _identifiers_in_text(document_text)
    if not candidates:
        fallback = [slots.get(key, "") for key in ("order", "error", "card")]
        candidates = [value for value in fallback if value]
    if not candidates:
        return text
    return f"{text} {rng.choice(candidates)}"


_ORDER_RE = re.compile(r"ORD-\d{4}-\d{5,6}")
_ERROR_RE = re.compile(r"ERR-[A-Z]{3}-\d{4}")
_PAN_RE = re.compile(r"\b(?:\d{4} ){3}\d{4}\b")
#: Dates as they appear in generated text: ``5 марта 2026``, ``5-mart 2026``, ``2026年3月5日``.
_NUMERIC_DATE_RE = re.compile(r"\b\d{1,2}[./-]\d{1,2}[./-](?:20\d{2}|\d{2})\b")
_ZH_DATE_RE = re.compile(r"20\d{2}年\d{1,2}月\d{1,2}日")
_MONTH_DATE_RE = re.compile(
    r"\b\d{1,2}[- ](?:январ[ья]?|феврал[ья]?|март[а]?|апрел[ья]?|ма[йя]|июн[ья]?|июл[ья]?|"
    r"август[а]?|сентябр[ья]?|октябр[ья]?|ноябр[ья]?|декабр[ья]?|"
    r"yanvar|fevral|mart|aprel|may|iyun|iyul|avgust|sentabr|oktabr|noyabr|dekabr|"
    r"Ocak|Şubat|Mart|Nisan|Mayıs|Haziran|Temmuz|Ağustos|Eylül|Ekim|Kasım|Aralık)"
    r"(?: \d{4})?",
    re.IGNORECASE,
)


def _identifiers_in_text(text: str) -> list[str]:
    """Identifiers present in ``text`` (sorted, de-duplicated: deterministic choice)."""
    found: set[str] = set()
    for pattern in (_ORDER_RE, _ERROR_RE, _PAN_RE):
        found.update(match.group(0) for match in pattern.finditer(text))
    return sorted(found)


def _dates_in_text(text: str) -> list[str]:
    """Date strings present in ``text`` (sorted, de-duplicated: deterministic choice)."""
    found: set[str] = set()
    for pattern in (_ZH_DATE_RE, _MONTH_DATE_RE, _NUMERIC_DATE_RE):
        found.update(match.group(0) for match in pattern.finditer(text))
    return sorted(found)


